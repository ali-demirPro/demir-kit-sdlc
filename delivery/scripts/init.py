#!/usr/bin/env python3
"""Generate a safe demir-kit project wiring from a fingerprint."""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

DEFAULT_UPSTREAM = "https://github.com/ali-demirPro/demir-kit-sdlc.git"

import detect as detect_mod  # noqa: E402
import profiles as profiles_mod  # noqa: E402
import resolver  # noqa: E402


def version() -> str:
    return (ROOT / "VERSION").read_text(encoding="utf-8").strip()


def repo_name(project: Path) -> str:
    try:
        raw = subprocess.check_output(
            ["git", "-C", str(project), "remote", "get-url", "origin"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "OWNER/REPO"
    match = re.search(r"github\.com[:/]([^/]+)/(.+?)(?:\.git)?$", raw)
    return f"{match.group(1)}/{match.group(2)}" if match else "OWNER/REPO"


DISTRIBUTION_ALIASES = {
    "app_store": "app_store_connect",
    "play": "play_console",
}


def normalize_distribution(kind: str) -> str:
    return DISTRIBUTION_ALIASES.get(kind, kind)


def profiles_for(fingerprint: dict) -> list[str]:
    expected: list[str] = []
    for surface in fingerprint.get("surfaces") or []:
        platforms = surface.get("platforms") or []
        stacks = surface.get("stacks") or []
        if "flutter" in stacks:
            expected.append("flutter-app")
            continue
        for platform in platforms:
            mapping = {
                "web": "web-app",
                "ios": "ios-app",
                "macos": "macos-app",
                "android": "android-app",
                "api": "api-service",
                "cli": "cli",
            }
            name = mapping.get(platform)
            if name and name not in expected:
                expected.append(name)
    hotspots = " ".join(fingerprint.get("risk_hotspots") or [])
    for overlay, keyword in (
        ("auth", "auth"),
        ("payments", "payments"),
        ("offline", "offline"),
    ):
        if keyword in hotspots and overlay not in expected:
            expected.append(overlay)
    order = [
        "web-app",
        "ios-app",
        "android-app",
        "flutter-app",
        "api-service",
        "cli",
        "library",
        "game",
        "landing",
        "data-ml",
    ]
    expected.sort(key=lambda name: order.index(name) if name in order else 99)
    return expected or ["web-app"]


def capabilities_for(fingerprint: dict) -> list[str]:
    signals = []
    for surface in fingerprint.get("surfaces") or []:
        signals.append(
            {
                "name": surface["name"],
                "surfaces": [surface["name"]],
                "platforms": surface.get("platforms") or [],
                "stacks": surface.get("stacks") or [],
                "distribution": [],
            }
        )
    for item in fingerprint.get("distribution") or []:
        kind = normalize_distribution(item["type"])
        signals.append(
            {
                "name": kind,
                "surfaces": [],
                "platforms": [],
                "stacks": [],
                "distribution": [kind],
            }
        )
    matched = resolver.match_capabilities(
        resolver.load_capabilities(), signals, ""
    )
    return sorted(matched)


def gate_script(fingerprint: dict) -> str:
    commands = []
    tests = fingerprint.get("test_commands") or {}
    if tests.get("behavior"):
        commands.append(tests["behavior"])
    if tests.get("typecheck"):
        commands.append(tests["typecheck"])
    if tests.get("lint"):
        commands.append(tests["lint"])
    if not commands:
        commands = [
            "echo 'gate-behavior: TODO configure real checks' >&2",
            "exit 1",
        ]
    body = "\n".join(commands)
    return (
        "#!/usr/bin/env bash\n"
        "# Generated by delivery/scripts/init.py — replace with real checks.\n"
        "set -euo pipefail\n"
        'CHECKPOINT="${1:?checkpoint id required, e.g. CP-1}"\n'
        'echo "gate-behavior: ${CHECKPOINT}"\n'
        f"{body}\n"
    )


def build(project: Path, repo: str | None = None, upstream: str = DEFAULT_UPSTREAM) -> dict:
    root = project.resolve()
    fingerprint = detect_mod.detect(root)
    target_repo = repo or repo_name(root)
    profile_names = profiles_for(fingerprint)
    profile = profile_names[0]
    detected = capabilities_for(fingerprint)
    caps = sorted(
        set(detected) | set(profiles_mod.profile_capabilities(profile_names))
    )

    surfaces = {}
    for surface in fingerprint.get("surfaces") or []:
        platforms = surface.get("platforms") or []
        surfaces[surface["name"]] = {
            "path": surface["path"],
            "stacks": surface.get("stacks") or [],
            "platforms": platforms,
            "gates": {
                "behavior": "./scripts/gate-behavior.sh {checkpoint}",
                "behavior_mode": "headless",
                "ui": any(
                    platform in {"web", "ios", "macos", "android"} for platform in platforms
                ),
                "ui_compare": "none",
            },
        }
    distributions = sorted(
        {
            normalize_distribution(item["type"])
            for item in fingerprint.get("distribution") or []
        }
    )
    distribution_platform = {
        "app_store_connect": "ios",
        "play_console": "android",
        "web_deploy": "web",
    }
    for kind in distributions:
        platform = distribution_platform.get(kind)
        target = None
        if platform:
            target = next(
                (
                    name
                    for name, spec in surfaces.items()
                    if platform in spec["platforms"]
                ),
                None,
            )
        if target is None and surfaces:
            target = next(iter(surfaces))
        if target:
            values = surfaces[target].setdefault("distribution", [])
            if kind not in values:
                values.append(kind)

    ecosystem = {
        "name": root.name,
        "products": {
            "app": {
                "description": "Generated by init.py; replace with real surfaces.",
                "surfaces": surfaces or {
                    "unknown": {
                        "path": ".",
                        "stacks": [],
                        "platforms": ["unknown"],
                        "gates": {
                            "behavior": "./scripts/gate-behavior.sh {checkpoint}",
                            "behavior_mode": "headless",
                            "ui": False,
                            "ui_compare": "none",
                        },
                    }
                },
            }
        },
        "tracker": {"provider": "github", "repo": target_repo},
    }
    kit_config = {
        "kit": {
            "root": "demir-kit",
            "version": version(),
            "protocol": "2",
            "upstream": {"git": upstream},
        },
        "tracker": {"provider": "github", "repo": target_repo},
        "orca": {
            "skills_required": ["orchestration", "orca-cli"],
            "integration": "delivery/protocol/execution.md",
            "gate_contract": "delivery/policies/quality-gates.md",
            "orchestration_readme": "delivery/protocol/execution.md",
        },
        "factory": {
            "default_profile": profile,
            "profiles": profile_names,
            "app_paths": fingerprint.get("app_paths") or ["src"],
        },
        "product": {"envision_required": False},
    }
    declared = {
        "version": 1,
        "include": detected,
        "exclude": [],
        "source": "init.py",
    }

    files = {
        "kit.config.yaml": "# Generated by delivery/scripts/init.py.\n"
        + yaml.safe_dump(kit_config, sort_keys=False, allow_unicode=True),
        "ecosystem.yaml": "# Generated by delivery/scripts/init.py.\n"
        + yaml.safe_dump(ecosystem, sort_keys=False, allow_unicode=True),
        ".kit/capabilities.yaml": "# Generated by delivery/scripts/init.py.\n"
        + yaml.safe_dump(declared, sort_keys=False, allow_unicode=True),
        "scripts/gate-behavior.sh": gate_script(fingerprint),
    }
    existing = [name for name in files if (root / name).exists()]
    return {
        "project": str(root),
        "profile": profile,
        "profiles": profile_names,
        "capabilities": caps,
        "fingerprint": fingerprint,
        "files": files,
        "existing": existing,
        "repo": target_repo,
    }


def apply_plan(plan: dict, force: bool = False) -> dict:
    root = Path(plan["project"])
    written: list[str] = []
    skipped: list[str] = []
    for name, content in plan["files"].items():
        path = root / name
        if path.exists() and not force:
            skipped.append(name)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        if name.endswith(".sh"):
            os.chmod(path, 0o755)
        written.append(name)
    return {"written": written, "skipped": skipped}


def render(plan: dict, applied: dict | None = None) -> str:
    lines = [
        f"project: {plan['project']}",
        "profiles: " + ", ".join(plan["profiles"]),
        f"capabilities: {', '.join(plan['capabilities']) or '-'}",
        "surfaces: " + (", ".join(
            f"{item['name']}[{','.join(item['platforms'])}]"
            for item in plan["fingerprint"].get("surfaces") or []
        ) or "-"),
        "files:",
    ]
    for name in plan["files"]:
        state = "exists" if name in plan["existing"] else "new"
        lines.append(f"  - {name} ({state})")
    if applied:
        lines.append("written: " + (", ".join(applied["written"]) or "-"))
        lines.append("skipped: " + (", ".join(applied["skipped"]) or "-"))
    else:
        lines.append("dry-run: --apply ile yazılır")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="generate project wiring")
    parser.add_argument("--project", type=Path, default=Path.cwd())
    parser.add_argument("--repo", help="owner/repo (default: git remote)")
    parser.add_argument(
        "--upstream", default=DEFAULT_UPSTREAM, help="kit upstream git URL"
    )
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    plan = build(args.project, args.repo, upstream=args.upstream)
    applied = None
    if args.apply:
        applied = apply_plan(plan, force=args.force)
    if args.json:
        print(
            json.dumps(
                {
                    "project": plan["project"],
                    "profile": plan["profile"],
                    "profiles": plan["profiles"],
                    "capabilities": plan["capabilities"],
                    "existing": plan["existing"],
                    "files": plan["files"],
                    "applied": applied,
                },
                ensure_ascii=False,
                indent=2,
            )
        )
    else:
        print(render(plan, applied))
    return 0


if __name__ == "__main__":
    sys.exit(main())
